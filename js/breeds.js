function getGroupById(id) {
  return BREED_GROUPS.find(g => g.id === id) || BREED_GROUPS[BREED_GROUPS.length - 1];
}
function getBreedDetails(name) {
  return BREED_DETAILS[name] || null;
}
function hasBreedTag(state, tag) {
  const d = getBreedDetails(state.dog.breedName);
  return d && Array.isArray(d.tags) && d.tags.includes(tag);
}
